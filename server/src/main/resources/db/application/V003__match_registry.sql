CREATE TABLE LOG004_MATCH_REGISTRY (
    C_GAME_ID TEXT NOT NULL PRIMARY KEY,
    T_MODE TEXT NOT NULL,
    J_HUMANS TEXT NOT NULL,
    T_INITIAL_HASH TEXT NOT NULL,
    N_OUTCOME_SEQUENCE INTEGER,
    T_OUTCOME_HASH TEXT,
    CHECK ((N_OUTCOME_SEQUENCE IS NULL AND T_OUTCOME_HASH IS NULL) OR
           (N_OUTCOME_SEQUENCE > 0 AND T_OUTCOME_HASH IS NOT NULL)),
    FOREIGN KEY (C_GAME_ID, N_OUTCOME_SEQUENCE) REFERENCES LOG003_MATCH_EVENTS(C_GAME_ID, N_SEQUENCE)
);;
CREATE TRIGGER LOG004_NO_DELETE BEFORE DELETE ON LOG004_MATCH_REGISTRY
BEGIN SELECT RAISE(ABORT, 'match registrations are permanent'); END;;
CREATE TRIGGER LOG004_FINALIZE_ONCE BEFORE UPDATE ON LOG004_MATCH_REGISTRY
WHEN OLD.N_OUTCOME_SEQUENCE IS NOT NULL OR NEW.N_OUTCOME_SEQUENCE IS NULL
 OR NEW.C_GAME_ID <> OLD.C_GAME_ID OR NEW.T_MODE <> OLD.T_MODE
 OR NEW.J_HUMANS <> OLD.J_HUMANS OR NEW.T_INITIAL_HASH <> OLD.T_INITIAL_HASH
 OR NOT EXISTS (SELECT 1 FROM LOG003_MATCH_EVENTS e WHERE e.C_GAME_ID=NEW.C_GAME_ID
     AND e.N_SEQUENCE=NEW.N_OUTCOME_SEQUENCE AND e.T_HASH=NEW.T_OUTCOME_HASH)
BEGIN SELECT RAISE(ABORT, 'match finalization is immutable'); END;;
CREATE TRIGGER LOG003_NO_EVENTS_AFTER_FINALIZATION BEFORE INSERT ON LOG003_MATCH_EVENTS
WHEN EXISTS (SELECT 1 FROM LOG004_MATCH_REGISTRY r WHERE r.C_GAME_ID=NEW.C_GAME_ID
    AND r.N_OUTCOME_SEQUENCE IS NOT NULL)
BEGIN SELECT RAISE(ABORT, 'match is finalized'); END;;
