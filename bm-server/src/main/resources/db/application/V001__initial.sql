CREATE TABLE BM_SCHEMA_VERSION (
    version INTEGER NOT NULL PRIMARY KEY,
    checksum TEXT NOT NULL,
    applied_at TEXT NOT NULL
);
CREATE TABLE USR001_CREDENTIALS (
    C_USERNAME TEXT NOT NULL PRIMARY KEY,
    T_EMAIL TEXT,
    T_SALTED_HASH TEXT NOT NULL,
    T_ROLE TEXT NOT NULL
);
CREATE INDEX IX_USR001_EMAIL ON USR001_CREDENTIALS(T_EMAIL);
CREATE TABLE USR002_DECKS (
    C_USERNAME TEXT NOT NULL REFERENCES USR001_CREDENTIALS(C_USERNAME),
    C_DECK_ID TEXT NOT NULL,
    J_DECK TEXT NOT NULL,
    PRIMARY KEY (C_USERNAME, C_DECK_ID)
);
CREATE TABLE LOG001_GAMES (
    C_GAME_ID TEXT NOT NULL PRIMARY KEY,
    T_PLAYERS TEXT,
    T_TYPE TEXT,
    T_DATE TEXT,
    T_STATUS TEXT,
    J_FULL_LOG TEXT NOT NULL
);
CREATE INDEX IX_LOG001_STATUS ON LOG001_GAMES(T_STATUS);
CREATE TABLE LOG002_WEB_CLIENT (
    C_TIMESTAMP TEXT NOT NULL PRIMARY KEY,
    T_ADDITIONAL TEXT,
    T_MESSAGE TEXT
);
